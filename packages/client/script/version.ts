#!/usr/bin/env bun
// Runs after `changeset version`: writes the SDK's package.json version into src/effect/version.ts, which the SDK
// sends on attach. A generated module instead of a JSON import, so consumers that typecheck the shipped .ts
// sources need no `resolveJsonModule`. The tunnel test "attaches with the published package version" fails on drift.

import pkg from "../package.json" with { type: "json" }

const file = Bun.file(new URL("../src/effect/version.ts", import.meta.url))
const after = `// Generated by packages/client/script/version.ts from package.json. Do not edit.\nexport const VERSION = ${JSON.stringify(pkg.version)};\n`
if ((await file.text().catch(() => "")) !== after) {
  await Bun.write(file, after)
  console.log(`packages/client/src/effect/version.ts → ${pkg.version}`)
}
